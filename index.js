let currentLang = 'ru';

function setLang(lang) {
  currentLang = lang;
  document.documentElement.lang = lang;
  const t = T[lang];

  // Update all data-t elements
  document.querySelectorAll('[data-t]').forEach(el => {
    const key = el.getAttribute('data-t');
    if (t[key] !== undefined) el.textContent = t[key];
  });

  // Update lang buttons
  document.querySelectorAll('.lang-btn').forEach(b => b.classList.remove('active'));
  const ab = document.querySelector(`.lang-btn[onclick="setLang('${lang}')"]`);
  if (ab) ab.classList.add('active');

  // Update page title
  const titles = {
    ru:'NS Plus – Профессиональное оборудование',
    uz:'NS Plus – Professional uskunalar',
    en:'NS Plus – Professional Equipment'
  };
  document.title = titles[lang];

  // Update tab labels
  document.querySelectorAll('.cat-tab[data-tab-key]').forEach(btn => {
    const k = btn.getAttribute('data-tab-key');
    if (t[k]) btn.textContent = t[k];
  });

  // Rebuild catalog in new language
  buildAllCatalogs();
}

