  function setLang(lang) {
    currentLang = lang;
  
    // Update html lang attribute
    document.documentElement.lang = lang;
  
    const t = translations[lang];
  
    // Update all data-t elements
    document.querySelectorAll('[data-t]').forEach(el => {
      const key = el.getAttribute('data-t');
      if (t[key] !== undefined) {
        // SVG text elements use textContent
        if (el.tagName === 'text') {
          el.textContent = t[key];
        } else {
          el.textContent = t[key];
        }
      }
    });
  
    // Update lang buttons
    document.querySelectorAll('.lang-btn').forEach(btn => {
      btn.classList.remove('active');
    });
    const activeBtn = document.querySelector(`.lang-btn[onclick="setLang('${lang}')"]`);
    if (activeBtn) activeBtn.classList.add('active');
  
    // Update page title
    const titles = { ru: 'NS Plus – Холодильные Камеры', uz: 'NS Plus – Sovutish Kameralari', en: 'NS Plus – Refrigeration Chambers' };
    document.title = titles[lang];
  }
  
