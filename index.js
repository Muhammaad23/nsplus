function buildCarousel(trackId, dotsId, countId, prevId, nextId, items) {
  const track = document.getElementById(trackId);
  const dotsEl = document.getElementById(dotsId);
  const countEl = document.getElementById(countId);
  const prevBtn = document.getElementById(prevId);
  const nextBtn = document.getElementById(nextId);
  if (!track) return;

  items.forEach(item => track.appendChild(createCard(item)));
  let current = 0;
  const visibleCount = () => window.innerWidth <= 480 ? 1 : 2;
  const pages = () => Math.max(1, items.length - visibleCount() + 1);

  function renderDots() {
    dotsEl.innerHTML = '';
    for (let i = 0; i < pages(); i++) {
      const d = document.createElement('span');
      d.className = 'c-dot' + (i === current ? ' active' : '');
      d.onclick = () => go(i);
      dotsEl.appendChild(d);
    }
  }

  function update() {
    const cardEl = track.children[0];
    const cardW = cardEl ? cardEl.offsetWidth : 0;
    track.style.transform = `translateX(-${current * (cardW + 12)}px)`;
    dotsEl.querySelectorAll('.c-dot').forEach((d, i) => d.classList.toggle('active', i === current));
    prevBtn.disabled = current === 0;
    nextBtn.disabled = current >= pages() - 1;
    countEl.textContent = `${current + 1} / ${items.length}`;
  }

  function go(n) {
    current = Math.max(0, Math.min(n, pages() - 1));
    update();
  }

  prevBtn.onclick = () => go(current - 1);
  nextBtn.onclick = () => go(current + 1);

  let touchX = 0;
  track.addEventListener('touchstart', e => { touchX = e.touches[0].clientX; }, { passive: true });
  track.addEventListener('touchend', e => {
    const dx = e.changedTouches[0].clientX - touchX;
    if (Math.abs(dx) > 40) go(dx < 0 ? current + 1 : current - 1);
  }, { passive: true });

  window.addEventListener('resize', () => {
    current = Math.min(current, pages() - 1);
    renderDots();
    update();
  });

  renderDots();
  update();
}

