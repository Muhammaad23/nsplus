function openLB(item) {
  const lang = currentLang;
  const title = typeof item.title === 'object' ? item.title[lang] : item.title;
  const desc  = typeof item.desc  === 'object' ? item.desc[lang]  : (item.desc || '');
  const specs = Array.isArray(item.specs)
    ? item.specs
    : (item.specs ? item.specs[lang] : []);

  document.getElementById('lbImg').src = item.img;
  document.getElementById('lbImg').alt = title;
  document.getElementById('lbTitle').textContent = title;
  document.getElementById('lbDesc').textContent  = desc;
  const badge = document.getElementById('lbBadge');
  badge.textContent = item.badge || '';
  badge.style.display = item.badge ? '' : 'none';
  document.getElementById('lbSpecs').innerHTML = specs.map(s => `<li>${s}</li>`).join('');
  document.getElementById('lb').classList.add('active');
  document.body.style.overflow = 'hidden';
}
function closeLB() {
  document.getElementById('lb').classList.remove('active');
  document.body.style.overflow = '';
}

